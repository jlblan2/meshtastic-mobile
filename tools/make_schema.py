#!/usr/bin/env python3
"""
Write ../schema.js: the Meshtastic protobuf message layouts the web app needs,
taken from the installed `meshtastic` Python package (pip install -U meshtastic,
then run this again to pick up new firmware fields).

    python tools/make_schema.py

schema.js sets window.MESH_SCHEMA = {version, messages, enums}:
  messages[full_name] = [[number, name, type, flags, type_name, oneof], ...]
      type  = protobuf wire descriptor type (9 string, 11 message, 14 enum, ...)
      flags = 1 repeated | 2 explicit presence (optional / oneof member)
  enums[full_name] = {NAME: number}
"""
import json
import os
from importlib.metadata import version

from meshtastic.protobuf import (admin_pb2, channel_pb2, config_pb2, localonly_pb2, mesh_pb2,
                                 module_config_pb2, portnums_pb2, telemetry_pb2)

ROOTS = [mesh_pb2, admin_pb2, channel_pb2, config_pb2, localonly_pb2, module_config_pb2,
         portnums_pb2, telemetry_pb2]

messages, enums, seen_files = {}, {}, set()


def add_enum(e):
    enums[e.full_name] = {v.name: v.number for v in e.values}


def add_message(m):
    fields = []
    for f in m.fields:
        repeated = getattr(f, "is_repeated", None)
        if repeated is None:
            repeated = f.label == f.LABEL_REPEATED
        oneof = f.containing_oneof
        real_oneof = oneof is not None and not (len(oneof.fields) == 1 and oneof.name.startswith("_"))
        presence = (not repeated) and f.type != f.TYPE_MESSAGE and bool(f.has_presence)
        type_name = None
        if f.type == f.TYPE_MESSAGE:
            type_name = f.message_type.full_name
        elif f.type == f.TYPE_ENUM:
            type_name = f.enum_type.full_name
        flags = (1 if repeated else 0) | (2 if presence or real_oneof else 0)
        fields.append([f.number, f.name, f.type, flags, type_name, oneof.name if real_oneof else None])
    messages[m.full_name] = fields
    for e in m.enum_types:
        add_enum(e)
    for n in m.nested_types:
        add_message(n)


def add_file(fd):
    if fd.name in seen_files:
        return
    seen_files.add(fd.name)
    for dep in fd.dependencies:
        add_file(dep)
    for m in fd.message_types_by_name.values():
        add_message(m)
    for e in fd.enum_types_by_name.values():
        add_enum(e)


for mod in ROOTS:
    add_file(mod.DESCRIPTOR)

# Drop google/nanopb descriptor messages: nothing the radio sends uses them.
messages = {k: v for k, v in messages.items() if k.startswith("meshtastic.")}
enums = {k: v for k, v in enums.items() if k.startswith("meshtastic.")}

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "schema.js")
body = json.dumps({"version": version("meshtastic"), "messages": messages, "enums": enums},
                  separators=(",", ":"), sort_keys=True)
with open(out, "w", encoding="utf-8", newline="\n") as fh:
    fh.write("// Generated by tools/make_schema.py from the meshtastic Python package. Do not edit.\n")
    fh.write("window.MESH_SCHEMA=" + body + ";\n")
print(f"{len(messages)} messages, {len(enums)} enums, {os.path.getsize(out)} bytes -> {os.path.normpath(out)}")
